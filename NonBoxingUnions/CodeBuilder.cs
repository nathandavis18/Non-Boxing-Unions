using System;
using System.Text;

namespace NonBoxingUnions;

internal sealed class CodeBuilder
{
	private const string IndentString = "    ";

	private readonly StringBuilder _builder = new();
	private bool _isStartOfLine = true;
	private int _indentLevel;

	public CodeBuilder(string? fileNamespace)
	{
		_builder.AppendLine("// <auto-generated/>");
		_builder.AppendLine("#nullable enable");
		_builder.AppendLine();

		if (!string.IsNullOrWhiteSpace(fileNamespace))
		{
			_builder.AppendLine(fileNamespace);
			_builder.AppendLine();
		}
	}

	public void Indent() => ++_indentLevel;
	public void UnIndent() => --_indentLevel;

	public CodeBuilder Append(string? text)
	{
		if (string.IsNullOrEmpty(text))
			return this;

		string[] lines = ReplaceLineEndings(text!).Split('\n');
		for (int i = 0; i < lines.Length; ++i)
		{
			if (i > 0)
			{
				_builder.AppendLine();
				_isStartOfLine = true;
			}

			if (lines[i].Length > 0)
			{
				WriteIndentIfNeeded();
				_builder.Append(lines[i]);
			}
		}

		return this;
	}

	public CodeBuilder AppendLine(string? text = null)
	{
		Append(text);
		_builder.AppendLine();
		_isStartOfLine = true;
		return this;
	}

	public IDisposable WriteBlock(string header, bool appendLineAtEnd = true)
	{
		AppendLine(header);
		AppendLine("{");
		Indent();
		return new BlockScope(this, appendLineAtEnd);
	}

	public override string ToString() => _builder.ToString();

	private void WriteIndentIfNeeded()
	{
		if (!_isStartOfLine)
			return;

		for (int i = 0; i < _indentLevel; ++i)
			_builder.Append(IndentString);
		_isStartOfLine = false;
	}

	private static string ReplaceLineEndings(string text) => text.Replace("\r\n", "\n");

	private sealed class BlockScope(CodeBuilder builder, bool appendLineAtEnd) : IDisposable
	{
		public void Dispose()
		{
			builder.UnIndent();
			if (appendLineAtEnd)
				builder.AppendLine("}");
			else
				builder.Append("}");
		}
	}
}
